/**
 * One-off generator: Natural Earth 110m land (public domain) -> compact land rings
 * consumed by src/components/location-search/world-land.data.ts.
 *
 * Usage: node docs/ai/demos/amkor/_tmp-build-world-land.mjs <input.geojson>
 */
import { readFileSync, writeFileSync } from 'node:fs';

const inputPath = process.argv[2];
const outputPath = 'src/components/location-search/world-land.data.ts';

const geojson = JSON.parse(readFileSync(inputPath, 'utf8'));

const ringBoxSpan = (ring) => {
  const lngs = ring.map((p) => p[0]);
  const lats = ring.map((p) => p[1]);
  return Math.max(Math.max(...lngs) - Math.min(...lngs), Math.max(...lats) - Math.min(...lats));
};

const round = (value) => Math.round(value * 10) / 10;

const simplifyRing = (ring) => {
  const out = [];
  for (const [lng, lat] of ring) {
    const point = [round(lng), round(lat)];
    const previous = out[out.length - 1];
    if (!previous || previous[0] !== point[0] || previous[1] !== point[1]) {
      out.push(point);
    }
  }
  return out;
};

const rings = [];
for (const feature of geojson.features) {
  const { type, coordinates } = feature.geometry;
  const polygons = type === 'Polygon' ? [coordinates] : coordinates;
  for (const polygon of polygons) {
    const outerRing = polygon[0];
    if (ringBoxSpan(outerRing) < 2.5) continue; // drop specks
    const simplified = simplifyRing(outerRing);
    if (simplified.length >= 4) rings.push(simplified);
  }
}

rings.sort((a, b) => b.length - a.length);

const body = rings
  .map((ring) => `  [${ring.map(([lng, lat]) => `[${lng},${lat}]`).join(',')}],`)
  .join('\n');

const file = `/**
 * Simplified world land outlines ([longitude, latitude] rings, outer rings only).
 * Source: Natural Earth 110m land (public domain), rounded to 0.1 degrees.
 * Generated by docs/ai/demos/amkor/_tmp-build-world-land.mjs — do not hand-edit.
 */
export type LandRing = [number, number][];

export const WORLD_LAND_RINGS: LandRing[] = [
${body}
];
`;

writeFileSync(outputPath, file);
console.log(`rings: ${rings.length}, points: ${rings.reduce((n, r) => n + r.length, 0)}`);
